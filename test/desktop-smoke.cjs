const { app, dialog } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { startDesktop } = require('../electron/main.cjs');
const { mockServer } = require('./mock-server.cjs');
const output = path.resolve(__dirname, '../acceptance');
let desktop, mock;
async function waitFor(fn, timeout = 15000) { const start = Date.now(); while (Date.now() - start < timeout) { try { const value = await fn(); if (value) return value; } catch {} await new Promise(resolve => setTimeout(resolve, 50)); } throw new Error('Desktop smoke condition timed out'); }
(async () => {
  await app.whenReady();
  await fs.mkdir(output, { recursive: true });
  const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'research-desk-desktop-'));
  mock = await mockServer();
  desktop = await startDesktop({ dataDir, settings: { endpoint: mock.endpoint, model: '本地模拟模型', maxRounds: 8, apiKey: 'local-smoke-only-key' }, paperEndpoint: mock.paperEndpoint });
  desktop.window.webContents.on('console-message', event => { if (event.level === 'error') console.error('[renderer]', event.message); });
  const evaluate = code => desktop.window.webContents.executeJavaScript(code, true).catch(error => { throw new Error(`页面脚本执行失败：${code.slice(0, 100)} ← ${error.message}`); });
  const read = async route => { const response = await fetch(`${desktop.origin}${route}`, { headers: { Authorization: `Bearer ${desktop.token}` } }); assert.equal(response.status, 200); return response.json(); };
  await waitFor(() => evaluate('document.body.dataset.ready === "true"'));
  await fs.writeFile(path.join(output, 'desktop-empty.png'), (await desktop.window.webContents.capturePage()).toPNG());
  assert.equal(await evaluate('typeof require'), 'undefined');
  assert.equal(await evaluate('typeof process'), 'undefined');
  assert.equal(await evaluate('typeof window.desk.session'), 'function');
  assert.equal(JSON.stringify(await read('/api/bootstrap')).includes('local-smoke-only-key'), false);
  await evaluate('document.querySelector("#new-project").click()');
  await waitFor(() => evaluate('Boolean(document.querySelector("#project-input"))'));
  await evaluate('document.querySelector("#project-input").value="人机协作中的信任校准"; document.querySelector("#direction-input").value="探索信任、依赖与协作表现之间的关系"; document.querySelector("#project-form").requestSubmit();');
  await waitFor(() => evaluate('document.querySelector("#project-name").textContent === "人机协作中的信任校准"'));
  await evaluate('document.querySelector("[data-view=library]").click()');
  await waitFor(() => evaluate('Boolean(document.querySelector("#search-query"))'));
  await evaluate('document.querySelector("#search-query").value="human AI trust"; document.querySelector("#search-form").requestSubmit();');
  await waitFor(() => evaluate('document.querySelectorAll(".paper-row").length === 1'));
  await evaluate('document.querySelector(".paper-actions .secondary").click()');
  await waitFor(async () => (await read('/api/bootstrap')).sources.length === 1);
  await evaluate('document.querySelector("[data-view=research]").click()');
  await waitFor(() => evaluate('Boolean(document.querySelector("#question"))'));
  await evaluate('document.querySelector("#question").value="综述信任校准研究，整理为研究笔记。"; document.querySelector("#composer").requestSubmit();');
  await waitFor(() => evaluate('Boolean(document.querySelector(".permission"))'));
  let data = await read('/api/bootstrap'); assert.equal(data.notes.length, 0); assert.equal(data.tasks[0].status, 'waiting_permission');
  await fs.writeFile(path.join(output, 'desktop-permission.png'), (await desktop.window.webContents.capturePage()).toPNG());
  await evaluate('document.querySelector(".permission-actions .primary").click()');
  await waitFor(async () => (await read('/api/bootstrap')).tasks[0].status === 'completed');
  await waitFor(() => evaluate('document.querySelector(".task-status")?.textContent === "已完成"'));
  data = await read('/api/bootstrap'); assert.equal(data.notes.length, 1); assert.match(data.tasks[0].output, /笔记已获准保存/);
  assert.equal(await evaluate('document.querySelectorAll(".message-text img").length'), 0);
  assert.equal(await evaluate('document.querySelector(".citation").textContent'), '[S1]');
  assert.equal(await evaluate('document.querySelector("#evidence-content").textContent.includes("A study of human–AI trust")'), true);
  assert.equal(await evaluate('Boolean(document.querySelector(".reasoning-part"))'), true);
  assert.equal(await evaluate('document.querySelectorAll(".tool-row.completed").length >= 2'), true);
  await fs.writeFile(path.join(output, 'desktop-research.png'), (await desktop.window.webContents.capturePage()).toPNG());
  // 排队 → 停止 → 自动发出；失败任务出现重发入口
  await evaluate('document.querySelector("#question").value="[stop] 阻塞中的研究"; document.querySelector("#composer").requestSubmit();');
  await waitFor(async () => (await read('/api/bootstrap')).tasks.some(t => t.status === 'running'));
  await evaluate('document.querySelector("#question").value="排队发送的后续问题"; document.querySelector("#composer").requestSubmit();');
  await waitFor(() => evaluate('Boolean(document.querySelector(".queued-chip"))'));
  await evaluate('document.querySelector("#stop-task").click()');
  await waitFor(async () => (await read('/api/bootstrap')).tasks.some(t => t.status === 'stopped'));
  await waitFor(async () => { const d = await read('/api/bootstrap'); return d.tasks.length === 3 && d.tasks[2].status === 'waiting_permission'; });
  await evaluate('document.querySelector(".permission-actions .primary").click()');
  await waitFor(async () => (await read('/api/bootstrap')).tasks[2].status === 'completed');
  assert.equal(await evaluate('document.querySelector("#thread").textContent.includes("排队发送的后续问题")'), true);
  assert.equal(await evaluate('document.querySelector("#thread").textContent.includes("重发这条研究问题")'), true);
  await fs.writeFile(path.join(output, 'desktop-queued.png'), (await desktop.window.webContents.capturePage()).toPNG());
  await evaluate('document.querySelector("[data-view=notes]").click()');
  assert.equal(await evaluate('document.querySelector("#note-reader").textContent.includes("信任校准研究笔记")'), true);
  const exported = path.join(dataDir, 'exported-note.md');
  const originalSave = dialog.showSaveDialog, originalOpen = dialog.showOpenDialog;
  dialog.showSaveDialog = async () => ({ canceled: false, filePath: exported });
  assert.equal(await evaluate(`window.desk.exportNote(${JSON.stringify(data.notes[0].id)})`), true);
  assert.match(await fs.readFile(exported, 'utf8'), /本地模拟测试笔记/);
  const imported = path.join(dataDir, 'imported-note.md'); await fs.writeFile(imported, '# 导入笔记\n\n用户提供的研究背景。');
  dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [imported] });
  const importedNote = await evaluate(`window.desk.importNote(${JSON.stringify(data.projects[0].id)})`);
  assert.equal(importedNote.title, 'imported-note'); assert.equal((await read('/api/bootstrap')).notes.length, 3); // 主任务 + 排队任务获准各一篇，加导入
  dialog.showSaveDialog = originalSave; dialog.showOpenDialog = originalOpen;
  await evaluate('document.querySelector("#model-status").click()');
  await waitFor(() => evaluate('document.querySelector("#settings-dialog").open'));
  assert.equal(await evaluate('document.querySelector("#key-input").value'), '');
  await evaluate('document.querySelector("#key-input").value="local-replacement-key"; document.querySelector("#settings-form").requestSubmit()');
  await waitFor(() => evaluate('!document.querySelector("#settings-dialog")?.open'));
  assert.equal((await fs.readFile(path.join(dataDir, 'model-settings.json'), 'utf8')).includes('local-replacement-key'), false);
  assert.equal(JSON.stringify(await read('/api/bootstrap')).includes('local-replacement-key'), false);
  desktop.window.setSize(1000, 720);
  await evaluate('document.querySelector("[data-view=research]").click()');
  assert.equal(await evaluate('document.querySelector("#composer").getBoundingClientRect().right <= innerWidth'), true);
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".evidence-panel")).display'), 'none');
  await evaluate('document.querySelector("#toggle-evidence").click()');
  assert.equal(await evaluate('document.querySelector("#toggle-evidence").getAttribute("aria-expanded")'), 'true');
  await evaluate('document.querySelector("#toggle-evidence").click()');
  await fs.writeFile(path.join(output, 'desktop-compact.png'), (await desktop.window.webContents.capturePage()).toPNG());
  await waitFor(() => desktop.workers.size === 0);
  const result = { passed: true, runtime: process.versions.electron, node: process.versions.node, platform: process.platform, cases: ['sandbox preload + protected session', 'project creation', 'Crossref search and save', 'real utilityProcess task', 'permission before note write', 'source citation', 'plain text injection safety', 'reasoning part and tool cards', 'queued send settles after stop', 'failed task resend entry', 'note import/export via IPC (dialogs stubbed)', 'encrypted key storage', 'compact evidence toggle', 'worker exit'], dataDirectory: dataDir };
  await fs.writeFile(path.join(output, 'desktop-smoke.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
  await desktop.shutdown(); await mock.close(); app.exit(0);
})().catch(async error => { console.error(error); if (desktop) await desktop.shutdown(); if (mock) await mock.close(); app.exit(1); });
